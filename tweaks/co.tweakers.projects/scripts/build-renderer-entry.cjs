"use strict";

// Projects keeps its feature modules as readable CommonJS sources. The
// renderer host, however, evaluates only index.js with module, exports, and
// console; it has no relative require resolver. This deterministic builder
// embeds the module graph behind a local resolver so the shipped entry stays
// self-contained without making renderer startup depend on Node.

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const ENTRY = path.join(ROOT, "index.js");
const MODULE_FILES = Object.freeze([
  "lib/common.js",
  "lib/state.js",
  "lib/policy.js",
  "lib/inventory.js",
  "lib/service.js",
  "lib/sidebar.js",
  "lib/settings.js",
  "lib/entry.js",
]);

function sourceFor(file) {
  return fs.readFileSync(path.join(ROOT, file), "utf8").replace(/\r\n/g, "\n");
}

function moduleId(file) {
  return `/${file.split(path.sep).join("/")}`;
}

function renderRendererEntry() {
  const modules = MODULE_FILES.map((file) => {
    const id = moduleId(file);
    return `${JSON.stringify(id)}: function (module, exports, require) {\n${sourceFor(file)}\n}`;
  });
  return [
    '"use strict";',
    "// Generated by scripts/build-renderer-entry.cjs. Do not edit directly.",
    "// The local module loader resolves bundled relative modules only.",
    "(function () {",
    "var __modules = {",
    modules.map((source) => `  ${source}`).join(",\n"),
    "};",
    "var __cache = {};",
    "var __externalRequire = typeof require === \"function\" ? require : null;",
    "function __resolve(from, request) {",
    "  var parts = from.split(\"/\");",
    "  parts.pop();",
    "  var segments = parts.slice();",
    "  var requested = request.split(\"/\");",
    "  for (var index = 0; index < requested.length; index += 1) {",
    "    var part = requested[index];",
    "    if (!part || part === \".\") continue;",
    "    if (part === \"..\") { if (segments.length > 1) segments.pop(); continue; }",
    "    segments.push(part);",
    "  }",
    "  var resolved = segments.join(\"/\");",
    "  if (__modules[resolved]) return resolved;",
    "  if (__modules[resolved + \".js\"]) return resolved + \".js\";",
    "  if (__modules[resolved + \"/index.js\"]) return resolved + \"/index.js\";",
    "  return null;",
    "}",
    "function __load(id) {",
    "  if (__cache[id]) return __cache[id].exports;",
    "  var factory = __modules[id];",
    "  if (!factory) throw new Error(\"Bundled Projects module is unavailable: \" + id);",
    "  var localModule = { exports: {} };",
    "  __cache[id] = localModule;",
    "  factory(localModule, localModule.exports, function (request) {",
    "    if (typeof request !== \"string\") throw new Error(\"Invalid bundled Projects module request\");",
    "    if (request.charAt(0) !== \".\") {",
    "      if (!__externalRequire) throw new Error(\"Node module is unavailable in the renderer: \" + request);",
    "      return __externalRequire(request);",
    "    }",
    "    var resolved = __resolve(id, request);",
    "    if (!resolved) throw new Error(\"Bundled Projects relative module is unavailable: \" + request);",
    "    return __load(resolved);",
    "  });",
    "  return localModule.exports;",
    "}",
    "module.exports = __load(\"/lib/entry.js\");",
    "}());",
    "",
  ].join("\n");
}

function checkRendererEntry() {
  const expected = renderRendererEntry();
  const actual = fs.readFileSync(ENTRY, "utf8");
  if (actual !== expected) {
    throw new Error("Projects index.js is stale; run node tweaks/co.tweakers.projects/scripts/build-renderer-entry.cjs");
  }
  return true;
}

function writeRendererEntry() {
  fs.writeFileSync(ENTRY, renderRendererEntry());
}

if (require.main === module) {
  if (process.argv.includes("--check")) checkRendererEntry();
  else writeRendererEntry();
}

module.exports = {
  MODULE_FILES,
  renderRendererEntry,
  checkRendererEntry,
  writeRendererEntry,
};
